DEFINE SCHEMA DCM_DEMO_3{{env_suffix}}.ANALYTICS
    COMMENT = 'Dynamic tables and functions for the food truck analytics';

DEFINE DYNAMIC TABLE DCM_DEMO_3{{env_suffix}}.ANALYTICS.ENRICHED_ORDER_DETAILS
WAREHOUSE = DCM_DEMO_3_WH{{env_suffix}}
TARGET_LAG = 'DOWNSTREAM'
REFRESH_MODE = ADAPTIVE
INITIALIZE = 'ON_SCHEDULE'
DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES'
COMMENT = 'One row per order line, joined to the menu and the customer'
-- CHANGE STEP 1 of 4: uncomment the line below to freeze orders older than one
-- day. Frozen rows are never recomputed, so the AI function in step 2 never
-- runs on them.
-- FROZEN WHERE (ORDER_TS < CURRENT_TIMESTAMP() - INTERVAL '1 day')
AS
SELECT
    O.ORDER_ID,
    O.ORDER_TS,
    O.QUANTITY,
    M.MENU_ITEM_NAME,
    M.ITEM_CATEGORY,
    M.SALE_PRICE_USD,
    M.COST_OF_GOODS_USD,
    (O.QUANTITY * M.SALE_PRICE_USD) AS LINE_ITEM_REVENUE,
    (O.QUANTITY * (M.SALE_PRICE_USD - M.COST_OF_GOODS_USD)) AS LINE_ITEM_PROFIT,
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME,
    INITCAP(C.CITY) AS CUSTOMER_CITY,
    O.TRUCK_BRAND_NAME
    -- CHANGE STEP 2 of 4: comment the line above and uncomment the two lines
    -- below. DIET_CLASSIFICATION goes last: a column inserted mid-SELECT fails
    -- the plan, because CREATE OR ALTER cannot reorder columns.
    -- O.TRUCK_BRAND_NAME,
    -- AI_CLASSIFY(M.MENU_ITEM_NAME, ['Healthy', 'Indulgent']):labels[0]::VARCHAR AS DIET_CLASSIFICATION
FROM DCM_DEMO_3{{env_suffix}}.RAW.ORDERS O
JOIN DCM_DEMO_3{{env_suffix}}.RAW.MENU M ON O.MENU_ITEM_ID = M.MENU_ITEM_ID
JOIN DCM_DEMO_3{{env_suffix}}.RAW.CUSTOMER C ON O.CUSTOMER_ID = C.CUSTOMER_ID;

DEFINE DYNAMIC TABLE DCM_DEMO_3{{env_suffix}}.ANALYTICS.CUSTOMER_SPENDING_SUMMARY
WAREHOUSE = DCM_DEMO_3_WH{{env_suffix}}
TARGET_LAG = '2 days'
REFRESH_MODE = ADAPTIVE
INITIALIZE = 'ON_SCHEDULE'
COMMENT = 'Lifetime orders and spend per customer'
AS
SELECT
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    CUSTOMER_CITY,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(LINE_ITEM_REVENUE) AS TOTAL_SPEND_USD,
    MIN(ORDER_TS) AS FIRST_ORDER_DATE,
    MAX(ORDER_TS) AS LATEST_ORDER_DATE
FROM DCM_DEMO_3{{env_suffix}}.ANALYTICS.ENRICHED_ORDER_DETAILS
GROUP BY CUSTOMER_ID, FIRST_NAME, LAST_NAME, CUSTOMER_CITY;

DEFINE DYNAMIC TABLE DCM_DEMO_3{{env_suffix}}.ANALYTICS.TRUCK_PERFORMANCE
WAREHOUSE = DCM_DEMO_3_WH{{env_suffix}}
TARGET_LAG = '12 hours'
REFRESH_MODE = ADAPTIVE
INITIALIZE = 'ON_SCHEDULE'
COMMENT = 'Revenue, profit and margin per truck brand'
AS
SELECT
    TRUCK_BRAND_NAME,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(LINE_ITEM_REVENUE) AS TOTAL_REVENUE,
    SUM(LINE_ITEM_PROFIT) AS TOTAL_PROFIT,
    DCM_DEMO_3{{env_suffix}}.ANALYTICS.CALCULATE_PROFIT_MARGIN(
        SUM(LINE_ITEM_REVENUE),
        SUM(LINE_ITEM_REVENUE) - SUM(LINE_ITEM_PROFIT)
    ) AS PROFIT_MARGIN_PCT
FROM DCM_DEMO_3{{env_suffix}}.ANALYTICS.ENRICHED_ORDER_DETAILS
GROUP BY TRUCK_BRAND_NAME;

-- SQL scalar UDF: gross margin as a percentage of revenue.
DEFINE FUNCTION DCM_DEMO_3{{env_suffix}}.ANALYTICS.CALCULATE_PROFIT_MARGIN(REVENUE NUMBER, COST NUMBER)
RETURNS NUMBER(10,2)
COMMENT = 'Gross margin % of revenue'
AS
$$
    CASE WHEN REVENUE = 0
        THEN 0
        ELSE ROUND(((REVENUE - COST) / REVENUE) * 100, 2)
    END
$$;

